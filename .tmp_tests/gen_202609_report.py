def set_text(elm, text):
    runs = elm.findall(qn('w:r'))
    for r in runs[1:]:
        elm.remove(r)
    if runs:
        t = runs[0].find(qn('w:t'))
        if t is None:
            t = runs[0].makeelement(qn('w:t'), {})
            runs[0].append(t)
        t.text = text
    else:
        r = elm.makeelement(qn('w:r'), {})
        t = r.makeelement(qn('w:t'), {})
        t.text = text
        r.append(t)
        elm.append(r)


